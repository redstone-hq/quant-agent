_COCKPIT_DIR = Path(__file__).parent / "static_cockpit"

# Generated by `scripts/status_board.py`, never committed: `data/`
# is gitignored precisely so machine-written files cannot become deploy drift.
_BOARD_DIR = board_dir()
_BOARD_FILE = _BOARD_DIR / "index.html"

# Desk diary — same gitignored `data/` posture as `/board`. Dated HTML
# pages are written on the live box; this process only serves them.
# `/diary` is a StaticFiles mount (html=True) so `/diary` and `/diary/`
# both resolve to index.html. GET-only middleware still covers it.

# Same production checkout `scripts/status_board.py` reads its own "box_sha"
# from (see PROD_CHECKOUT there). Duplicated as a plain constant rather than
# imported: `scripts/` depends on `src/`, not the other way around, and this
# is one path, not a library to share.
_PROD_CHECKOUT = Path("/home/qamc/quant-agent")

#: Pulls the board's build-time SHA back out of the <meta> tag
#: `scripts/status_board.py` stamps into the page it generates.
_BUILT_SHA_RE = re.compile(r'<meta name="qamc-board-built-sha" content="([0-9a-fA-F]*)"')

logger = logging.getLogger(__name__)

_SAFE_METHODS = {"GET", "HEAD", "OPTIONS"}


class _GetOnlyMiddleware(BaseHTTPMiddleware):
    async def dispatch(self, request: Request, call_next):
        if request.method not in _SAFE_METHODS:
            return JSONResponse(
                status_code=405,
                content={"detail": "Mission Control API is read-only: GET only"},
            )
        return await call_next(request)


# --------------------------------------------------------------------------
# /board — served by hand, not StaticFiles, so freshness can be checked
# against a fact (the running commit) instead of a clock. See
# `scripts/status_board.py`'s module docstring: this board would rather say
# "unknown" than say something false, and a time-based staleness banner
# cannot honour that — a quiet weekend legitimately produces an old page
# with nothing wrong. The one thing that DOES mean something moved on is the
# page's build-time commit no longer matching the commit running right now.
# --------------------------------------------------------------------------


def _board_live_sha() -> str | None:
    """Read the commit the production box is running, right now.

    Mirrors `_prod_git("rev-parse", "HEAD")` in scripts/status_board.py: a
    direct git read first (works when this process itself runs as `qamc`),
    falling back to the same passwordless-sudo path the board relies on.
    Never raises. Returns None — never a guess — if neither works, so the
    caller reports the freshness as unknown rather than implying it's fine.
    """
    for cmd in (
        ["git", "-C", str(_PROD_CHECKOUT), "rev-parse", "HEAD"],
        ["sudo", "-n", "-u", "qamc", "git", "-C", str(_PROD_CHECKOUT), "rev-parse", "HEAD"],
    ):
        try:
            p = subprocess.run(cmd, capture_output=True, text=True, timeout=5)
        except Exception:  # noqa: BLE001 - a broken probe must not break the page
            continue
        sha = p.stdout.strip()
        if p.returncode == 0 and sha:
            return sha
    return None


def _board_built_sha(board_html: str) -> str | None:
    """Pull the version the board was generated from out of its own markup.

    None if the page carries no stamp at all (an older page, or the box's
    SHA was unreadable at build time) — never an empty-string stand-in that
    could accidentally compare equal to something.
    """
    m = _BUILT_SHA_RE.search(board_html)
    if not m or not m.group(1):
        return None
    return m.group(1)


def _freshness_banner(built_sha: str | None, live_sha: str | None) -> str:
    """A prominent banner to inject at the top of the page, or "" for none.

    Three outcomes, and only three:
      - both known and equal   -> "" (say nothing; the page is current)
      - both known and unequal -> a plain "this has changed" banner
      - either side unknown    -> a plain "freshness UNKNOWN" banner

    Reuses the page's own --crit / --crit-bg variables via the existing
    `.stale` class already defined in scripts/status_board_template.html —
    no new colours, no script; the decision is made here, server-side,
    before the page is ever sent.
    """
    if not built_sha or not live_sha:
        return (
            '<div class="stale"><b>Board freshness: UNKNOWN.</b> '
            "This page's build version could not be compared against the "
            "system currently running, so there is no way to confirm "
            "whether it is up to date.</div>"
        )
    if built_sha != live_sha:
        return (
            '<div class="stale"><b>This board is out of date.</b> '
            "The desk has been updated since this page was built, so what "
            "follows is a snapshot rather than the current picture. If this "
            "does not clear on its own within a few minutes, the rebuild "
            "that should have refreshed it is not running."
            f'<span class="stale-detail">built {built_sha[:9]} &middot; '
            f"running {live_sha[:9]}</span></div>"
        )
    return ""


def _inject_banner(board_html: str, banner: str) -> str:
    """Place the banner right at the top of the visible page. No-op for "".

    `<div class="wrap">` is the page's own outer container — present in
    every board the template produces — so this needs no coordination with
    `scripts/status_board.py` beyond that container existing.
    """
    if not banner:
        return board_html
    marker = '<div class="wrap">'
    idx = board_html.find(marker)
    if idx == -1:
        return banner + board_html
    at = idx + len(marker)
    return board_html[:at] + banner + board_html[at:]


#: The most recent SUCCESSFUL read of what is in flight, kept so a failed
#: re-read can show a dated list rather than nothing. Process-local, like
#: the ETag cache it sits beside.
_last_good_in_flight: inflight.InFlight | None = None


def _refresh_in_flight(board_html: str) -> str:
    """Re-read what is being built, right now, and swap it into the page.

    The board file is rebuilt when the backlog, the plan or the deployed
    commit changes. An open pull request changing does none of those \u2014 it
    happens on GitHub, not on this box \u2014 so a build-time copy of that
    section goes stale between rebuilds with nothing to trigger a new one.
    Rather than add a clock (retired once already; any interval would be a
    number nobody can justify), the section is re-read when the page is
    asked for. Conditional requests make an unchanged re-read free, so
    opening the page repeatedly costs nothing against GitHub's limit.

    Degrades the same way the rest of the page does: a failed read renders
    as "could not read", with the last successful read shown, dated, under
    it if this process has one \u2014 never as an empty list, and never as the
    build-time copy passing for current. A page with no fenced section (an
    older build) is returned untouched. Never raises.
    """
    global _last_good_in_flight
    if inflight.START_MARK not in board_html:
        return board_html
    try:
        now_read = inflight.read_in_flight()
        if now_read.readable:
            _last_good_in_flight = now_read
        fresh = inflight.render_in_flight(now_read, last_good=_last_good_in_flight)
        return inflight.refresh_in_flight_html(board_html, fresh)
    except Exception as exc:  # noqa: BLE001 - the page must still be served
        logger.warning("in-flight refresh failed: %s", exc)
        return board_html


def _render_board() -> HTMLResponse:
    if not _BOARD_FILE.is_file():
        return HTMLResponse(
            "<p>The status board has not been generated yet. It is written "
            "by <code>scripts/status_board.py</code>, which runs whenever the "
            "work backlog or the plan changes \u2014 check back shortly.</p>",
            status_code=200,
        )
    board_html = _refresh_in_flight(_BOARD_FILE.read_text())
    banner = _freshness_banner(_board_built_sha(board_html), _board_live_sha())
    return HTMLResponse(_inject_banner(board_html, banner))


def create_app() -> FastAPI:
    app = FastAPI(
        title="QAMC Mission Control API",
        description=(
            "Stage 2 — thin, read-only adapter over quant-agent's existing "
            "canonical state. Never places, cancels, or modifies broker "
            "orders; never calls an AI agent or the Portfolio Manager; "
            "trading runs unaffected by this process's presence or absence."
        ),
        version="0.1.0",
    )
    app.add_middleware(_GetOnlyMiddleware)
    app.include_router(live_router, tags=["live"])
    app.include_router(chopping_block_router, tags=["chopping-block"])
    app.include_router(route_events_router, tags=["route-events"])
    app.include_router(pruning_router, tags=["pruning"])
    app.include_router(history_router, tags=["history"])
    app.include_router(evidence_router, tags=["evidence"])
    app.include_router(journal_router, tags=["journal"])
    app.include_router(research_router, tags=["research"])
    app.include_router(scorecard_router, tags=["scorecard"])

    if _STATIC_DIR.is_dir():
        # Stage 3 cockpit — static assets only, no templating/server state.
        # Mounted last and under its own path so it never shadows the JSON
        # routes above or the `/` service-meta route below.
        app.mount("/ui", StaticFiles(directory=str(_STATIC_DIR), html=True), name="ui")

    if _COCKPIT_DIR.is_dir():
        # Stage 6 cockpit — same static-assets-only posture as /ui above.
        app.mount("/cockpit", StaticFiles(directory=str(_COCKPIT_DIR), html=True), name="cockpit")

    # Desk diary — gitignored `data/diary/`, same StaticFiles+html posture
    # as /ui and /cockpit. ensure_diary_dir() creates the folder and a
    # placeholder index when nothing has been written yet, so the mount
    # never 500s on a fresh box. Listing rebuild:
    # `python scripts/rebuild_desk_diary_index.py`.
    app.mount(
        "/diary",
        StaticFiles(directory=str(ensure_diary_dir()), html=True),
        name="diary",
    )

    # The human status board (`scripts/status_board.py`, rebuilt by the
    # quant-agent-status-board.path unit whenever docs/WORK.md, docs/phases.yaml
    # or the deployed commit changes — there is no timer). It
    # lives under `data/`, which is gitignored, so regenerating it can never
    # dirty the production checkout — the deploy-drift problem that cost a
    # day on 2026-08-28 started exactly that way, with a file the box edited
    # that git also tracked. Unlike /ui and /cockpit above this is a small
    # handler, not a StaticFiles mount: it has to compare the page's built-
    # from commit against the commit running right now on every request (see
    # `_render_board` above), and it has to keep answering — with a plain
    # message, not a 404/stack trace — even before the board has ever been
    # generated, which StaticFiles cannot do. Read-only either way; the
    # GET-only middleware still covers it.
    @app.get("/board", include_in_schema=False)
    @app.get("/board/", include_in_schema=False)
    def board() -> HTMLResponse:
        return _render_board()

    @app.exception_handler(Exception)
    async def _unhandled_exception_handler(request: Request, exc: Exception):
        logger.warning("Unhandled exception on %s %s: %s", request.method, request.url.path, exc)
        return JSONResponse(status_code=500, content={"detail": "internal error"})

    @app.get("/", tags=["meta"])
    def root() -> dict:
        return {"service": "qamc-mission-control-api", "status": "ok"}

    return app


app = create_app()
